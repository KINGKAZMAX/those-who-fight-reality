/* Build runtime catalog from untouched generated assets and native LF2 metadata. */
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const inventory = JSON.parse(fs.readFileSync(path.join(root, 'assets/runtime/native-animation-inventory.json')))
const names = {xiaoyi:11,linxia:2,zhouqi:8,chenye:4,tangli:9,shenzhou:10,'paper-monster':30,'stapler-monster':31,'clock-monster':32}
const replacements = {}
for (const file of fs.readdirSync(path.join(root,'assets/runtime')).filter(name => /^animation-.*\.json$/.test(name) && !name.includes('patches'))) {
  const data = JSON.parse(fs.readFileSync(path.join(root,'assets/runtime',file)))
  const records = Array.isArray(data) ? data : data.assets
  for (const record of records || []) {
    const id = Number.isInteger(record.id) ? record.id : names[record.id]
    if (!id || !record.nativeSource) throw new Error('Invalid provenance: ' + file)
    const absolute = path.join(root,'vendor/F.LF/game/art',record.replacement)
    if (!fs.existsSync(absolute)) throw new Error('Missing animation: ' + absolute)
    const key = id + ':' + record.nativeSource + (record.sheetStart === undefined ? '' : ':' + record.sheetStart)
    replacements[key] = {file:record.replacement,columns:record.columns,rows:Math.floor(record.rows),rowOffset:record.rowOffset||0,columnOffset:record.columnOffset||0,registered:true,reviewed:false}
  }
}
const patches = []
for (const file of fs.readdirSync(path.join(root,'assets/runtime')).filter(name => /^animation-patches-.*\.json$/.test(name))) {
  const data = JSON.parse(fs.readFileSync(path.join(root,'assets/runtime',file)))
  for (const record of (Array.isArray(data) ? data : data.assets || data.patches || [])) {
    const patch=Object.assign({},record,{objectId:record.objectId||record.id,file:record.file||record.replacement,registered:true,reviewed:false})
    if (!Number.isInteger(patch.objectId)||!patch.file) throw new Error('Invalid patch metadata: '+file)
    if (!fs.existsSync(path.join(root,'vendor/F.LF/game/art',patch.file))) throw new Error('Missing patch: '+patch.file)
    patches.push(patch)
  }
}
const catalog = {version:'native-pictures-20261018-2',objects:inventory.objects,replacements,patches}
const content='/* Generated by tools/build_native_animation_catalog.cjs. */\ndefine('+JSON.stringify(catalog,null,2)+')\n'
const publish=process.argv.includes('--publish')
if(publish){
  const proof=JSON.parse(fs.readFileSync(path.join(root,'docs/verification/native-animation/report.json')))
  const hash=require('node:crypto').createHash('sha256').update(content).digest('hex')
  const verificationHash=require('./native_animation_digest.cjs')(root,content)
  if(proof.passed!==true||proof.generatedSheets!==Object.keys(replacements).length||proof.catalogHash!==hash||proof.verificationHash!==verificationHash||!proof.atomicReject||proof.boundErrors.length||proof.alphaErrors.length||proof.errors.length)throw new Error('Candidate has not passed raster/atomic verification')
}
const output=path.join(root,'vendor/F.LF/game',publish?'native-animation-data.js':'native-animation-candidate.js')
fs.writeFileSync(output+'.tmp',content)
fs.renameSync(output+'.tmp',output)
console.log('Registered native sheets:', inventory.objects.reduce((n,o)=>n+o.sheets.length,0), 'redrawn sheets:', Object.keys(replacements).length)
